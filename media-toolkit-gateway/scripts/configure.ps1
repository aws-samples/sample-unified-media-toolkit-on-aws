# configure.ps1 — PowerShell twin of configure.sh: connect Claude Code,
# Codex CLI and/or Kiro to the Unified Media Toolkit gateway on Windows,
# and install the skills.
#
#   .\configure.ps1 -Agent claude|codex|kiro|all `
#       [-SecretName /media-toolkit-gateway/dev/gateway-credentials] `
#       [-Region eu-west-1]
#   .\configure.ps1 -RefreshToken        # Kiro: re-mint the 12h token
#
# Behavior-identical to configure.sh (keep the two in sync), with the
# Windows substitutions:
#   - the headers helper is invoked as
#     "powershell.exe -NoProfile -ExecutionPolicy Bypass -File <wrapper>.ps1"
#     (a bare .ps1 path will not execute from the shell agents spawn)
#   - skills are COPIED, not symlinked (symlinks need Developer Mode);
#     re-run this script after a kit update to refresh the copies
# Never writes the clientSecret anywhere. Merges touch only the
# "media-toolkit" entry and back up the file first. Idempotent.
# Targets Windows PowerShell 5.1 (preinstalled on Windows 10/11); also
# runs on PowerShell 7+. Requires AWS CLI v2 on PATH.

[CmdletBinding()]
param(
    [string]$Agent = "",
    [string]$SecretName = "",
    [string]$Region = "",
    [switch]$RefreshToken
)
$ErrorActionPreference = "Stop"
[Net.ServicePointManager]::SecurityProtocol = `
    [Net.ServicePointManager]::SecurityProtocol -bor `
    [Net.SecurityProtocolType]::Tls12

$Here = Split-Path -Parent $MyInvocation.MyCommand.Path
$KitRoot = Split-Path -Parent $Here
$ServerKey = "media-toolkit"

# default precedence: parameter > env var > kit.env > the legacy name
$KitSecret = $null; $KitRegion = $null
$KitEnv = Join-Path $KitRoot "kit.env"
if (Test-Path $KitEnv) {
    foreach ($line in Get-Content $KitEnv) {
        if ($line -match '^\s*KIT_SECRET_NAME\s*=\s*"?([^"#]+)"?') {
            $KitSecret = $Matches[1].Trim() }
        if ($line -match '^\s*KIT_REGION\s*=\s*"?([^"#]+)"?') {
            $KitRegion = $Matches[1].Trim() }
    }
}
if (-not $SecretName) {
    $SecretName = if ($env:GATEWAY_SECRET_NAME) { $env:GATEWAY_SECRET_NAME }
                  elseif ($KitSecret) { $KitSecret }
                  else { "/media-toolkit-gateway/dev/gateway-credentials" }
}
if (-not $Region) {
    $Region = if ($env:AWS_REGION) { $env:AWS_REGION }
              elseif ($KitRegion) { $KitRegion }
              else { "eu-west-1" }
}

if (-not (Get-Command aws -ErrorAction SilentlyContinue)) {
    Write-Error "error: the AWS CLI is required and was not found on PATH"
    exit 1
}

$CredsJson = aws secretsmanager get-secret-value --secret-id $SecretName `
    --region $Region --query SecretString --output text 2>$null
if ($LASTEXITCODE -ne 0 -or -not $CredsJson) {
    Write-Host "error: cannot read the credentials secret '$SecretName' in"
    Write-Host "       $Region - your AWS identity needs secretsmanager:GetSecretValue"
    Write-Host "       on it (or pass the right -SecretName / -Region)"
    exit 1
}
$Creds = $CredsJson | ConvertFrom-Json
$GatewayUrl = $Creds.endpointUrl
if (-not ($GatewayUrl -like "https://*")) {
    Write-Error ("error: the secret has no endpointUrl - is it the gateway " +
                 "credentials bundle?")
    exit 1
}

# ── the ONE auth primitive: a per-deployment wrapper satisfying every
# helper contract (JSON headers on stdout). The HELPER STRING the agent
# configs carry is the full powershell invocation of that wrapper. ──
$sha = [System.Security.Cryptography.SHA256]::Create()
$DeployKey = ([BitConverter]::ToString($sha.ComputeHash(
    [Text.Encoding]::UTF8.GetBytes("$SecretName|$Region"))) `
    -replace "-", "").ToLower().Substring(0, 16)
$Wrapper = Join-Path $Here "gateway_headers.$DeployKey.ps1"
@"
# generated by configure.ps1 - headers helper for '$ServerKey'
`$env:GATEWAY_SECRET_NAME = "$SecretName"
`$env:AWS_REGION = "$Region"
& "$Here\get_gateway_token.ps1"
exit `$LASTEXITCODE
"@ | Set-Content -Path $Wrapper -Encoding UTF8
$HelperCmd = "powershell.exe -NoProfile -ExecutionPolicy Bypass -File `"$Wrapper`""

function Mint-Token {  # always FRESH - never serve a cached token as "new"
    # run the wrapper IN-PROCESS: host-agnostic (powershell.exe is the
    # string agents spawn on Windows; this script itself may run under
    # pwsh), and the wrapper's env assignments are the same values this
    # script already carries
    $env:GATEWAY_TOKEN_NO_CACHE = "1"
    try {
        $out = & $Wrapper
        if ($LASTEXITCODE -ne 0) { throw "token helper failed" }
        return (($out | Out-String | ConvertFrom-Json).Authorization `
                -replace "^Bearer ", "")
    } finally {
        Remove-Item Env:GATEWAY_TOKEN_NO_CACHE -ErrorAction SilentlyContinue
    }
}

function Backup-File([string]$Path) {
    if (Test-Path $Path) {
        Copy-Item $Path "$Path.bak.$(Get-Date -Format yyyyMMddHHmmss)"
    }
}

function Copy-Skills([string]$Target) {
    New-Item -ItemType Directory -Force -Path $Target | Out-Null
    Get-ChildItem (Join-Path $KitRoot "skills") -Directory |
        ForEach-Object {
            Copy-Item $_.FullName -Destination $Target -Recurse -Force
        }
    Write-Host "  skills copied into $Target (re-run after a kit update)"
}

function Set-Prop($Obj, [string]$Name, $Value) {
    if ($Obj.PSObject.Properties[$Name]) { $Obj.$Name = $Value }
    else { $Obj | Add-Member -NotePropertyName $Name -NotePropertyValue $Value }
}

function Merge-McpJson([string]$Cfg, [hashtable]$Fields) {
    if (-not (Test-Path $Cfg) -or
        -not (Get-Content $Cfg -Raw).Trim()) {
        New-Item -ItemType Directory -Force -Path (Split-Path $Cfg) | Out-Null
        Set-Content -Path $Cfg -Value "{}"
    }
    Backup-File $Cfg
    $doc = Get-Content $Cfg -Raw | ConvertFrom-Json
    if (-not $doc.PSObject.Properties["mcpServers"]) {
        Set-Prop $doc "mcpServers" ([pscustomobject]@{})
    }
    $servers = $doc.mcpServers
    if (-not $servers.PSObject.Properties[$ServerKey]) {
        Set-Prop $servers $ServerKey ([pscustomobject]@{})
    }
    # merge INTO any existing entry (user-added fields survive)
    $entry = $servers.$ServerKey
    foreach ($k in $Fields.Keys) { Set-Prop $entry $k $Fields[$k] }
    $doc | ConvertTo-Json -Depth 32 | Set-Content -Path $Cfg -Encoding UTF8
}

function Configure-KiroToken {
    # WORKSPACE-level config, deliberately (./.kiro, beside the skills):
    # Kiro merges workspace over user level, so this entry can never be
    # shadowed. Run from the project you use Kiro in.
    $cfg = ".\.kiro\settings\mcp.json"
    $token = Mint-Token
    Merge-McpJson $cfg @{
        url = $GatewayUrl
        headers = [pscustomobject]@{ Authorization = "Bearer $token" }
    }
    # defaults only on a NEW entry - an existing autoApprove (e.g. ["*"])
    # is the user's call; never default to "*" (the bundle's gateway
    # carries admin tools)
    $doc = Get-Content $cfg -Raw | ConvertFrom-Json
    $entry = $doc.mcpServers.$ServerKey
    $dirty = $false
    if (-not $entry.PSObject.Properties["disabled"]) {
        Set-Prop $entry "disabled" $false; $dirty = $true
    }
    if (-not $entry.PSObject.Properties["autoApprove"]) {
        Set-Prop $entry "autoApprove" @(); $dirty = $true
    }
    if ($dirty) {
        $doc | ConvertTo-Json -Depth 32 | Set-Content -Path $cfg -Encoding UTF8
    }
    Write-Host ("  $cfg updated (token valid ~12 h; re-run with " +
                "-RefreshToken from this project; Kiro hot-reloads on save)")
    # the file carries a bearer token - it must never be committed
    if (Get-Command git -ErrorAction SilentlyContinue) {
        git rev-parse --is-inside-work-tree 2>$null | Out-Null
        if ($LASTEXITCODE -eq 0) {
            # git accepts forward slashes on every platform
            git check-ignore -q ($cfg -replace '\\', '/') 2>$null | Out-Null
            if ($LASTEXITCODE -ne 0) {
                Write-Host ("  WARNING: $cfg is NOT gitignored and contains " +
                    "a bearer token - add '.kiro/' to .gitignore before committing")
            }
        }
    }
}

if ($RefreshToken) { Configure-KiroToken; exit 0 }

if (-not $Agent) {
    Write-Host "error: -Agent is required: claude, codex, kiro, or all"
    exit 1
}
if ($Agent -eq "all") { $Agent = "claude,codex,kiro" }

foreach ($a in $Agent -split ",") {
    switch ($a.Trim()) {

        "claude" {
            Write-Host "Claude Code:"
            $cfg = ".\.mcp.json"
            Merge-McpJson $cfg @{
                type = "http"; url = $GatewayUrl; headersHelper = $HelperCmd
            }
            Write-Host "  $cfg updated (auth auto-refreshes via headersHelper)"
            Copy-Skills ".\.claude\skills"
            Write-Host "  NOTE: Claude Code asks you to approve this project-scoped"
            Write-Host "        server on first launch - accept the prompt once."
        }

        "codex" {
            Write-Host "Codex CLI:"
            $cfg = Join-Path $HOME ".codex\config.toml"
            New-Item -ItemType Directory -Force -Path (Split-Path $cfg) | Out-Null
            if (-not (Test-Path $cfg)) { Set-Content -Path $cfg -Value "" }
            Backup-File $cfg
            $s = Get-Content $cfg -Raw
            if ($null -eq $s) { $s = "" }
            $helperToml = $HelperCmd -replace '\\', '\\\\' -replace '"', '\"'
            $block = ("# >>> media-toolkit (managed by configure.ps1) >>>`n" +
                      "[mcp_servers.media-toolkit]`n" +
                      "url = `"$GatewayUrl`"`n" +
                      "http_headers_helper = `"$helperToml`"`n" +
                      "# <<< media-toolkit <<<`n")
            $pat = "(?s)# >>> media-toolkit.*?# <<< media-toolkit <<<\r?\n"
            if ($s -match $pat) {
                $s = [regex]::Replace($s, $pat, $block)
            } elseif ($s -match "(?m)^\s*\[mcp_servers\.media-toolkit\]") {
                # a hand-written table outside our markers would become a
                # DUPLICATE TOML table if we appended - refuse, never corrupt
                Write-Error ("error: ~/.codex/config.toml already defines " +
                    "[mcp_servers.media-toolkit] outside the managed block - " +
                    "remove or rename that table, then re-run")
                exit 1
            } else {
                if ($s -and -not $s.EndsWith("`n")) { $s += "`n" }
                $s += $block
            }
            Set-Content -Path $cfg -Value $s -Encoding UTF8
            Write-Host "  $cfg updated (auth auto-refreshes via http_headers_helper)"
            Copy-Skills ".\.agents\skills"
        }

        "kiro" {
            Write-Host "Kiro:"
            Configure-KiroToken
            Copy-Skills ".\.kiro\skills"
        }

        default {
            Write-Host "error: unknown agent '$a' - claude, codex, kiro, or all"
            exit 1
        }
    }
}

Write-Host ""
Write-Host "Done. Gateway: $GatewayUrl"
Write-Host "Smoke test: ask your agent to call a *___describe_tool and"
Write-Host "summarize the output contract."
