#!/usr/bin/env bash
#
# configure.sh — connect Claude Code, Codex CLI and/or Kiro to the
# Unified Media Toolkit gateway, and install the skills.
#
#   ./configure.sh --agent claude|codex|kiro|all \
#       [--secret-name /media-toolkit-gateway/dev/gateway-credentials] \
#       [--region eu-west-1]
#   ./configure.sh --refresh-token        # Kiro: re-mint the 12h token
#
# Reads the deployment's credentials secret to discover the gateway
# endpoint (nothing is hardcoded), then per agent:
#   claude  merge the "media-toolkit" server into ./.mcp.json
#           (headersHelper -> a generated wrapper; auto-refreshing)
#           + symlink skills into ./.claude/skills/
#   codex   managed block in ~/.codex/config.toml
#           (http_headers_helper -> the same wrapper; auto-refreshing)
#           + symlink skills into ./.agents/skills/
#   kiro    merge the server into ~/.kiro/settings/mcp.json with a
#           STATIC 12h bearer token + symlink skills into ./.kiro/skills/
#
# Never writes the clientSecret anywhere. Merges touch only the
# "media-toolkit" entry and back up the file first. Idempotent.
# macOS/Linux; on Windows use configure.ps1 (the PowerShell twin).

set -euo pipefail

HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
KIT_ROOT="$(cd "$HERE/.." && pwd)"
SERVER_KEY="media-toolkit"

# default precedence: env var > kit.env (written into the published kit
# by the deployment's KitPublisher — points at this kit's OWN gateway;
# absent in a repo checkout) > the legacy well-known name
[[ -f "$KIT_ROOT/kit.env" ]] && . "$KIT_ROOT/kit.env"
SECRET_NAME="${GATEWAY_SECRET_NAME:-${KIT_SECRET_NAME:-/media-toolkit-gateway/dev/gateway-credentials}}"
REGION="${AWS_REGION:-${KIT_REGION:-eu-west-1}}"
AGENTS=""
REFRESH_ONLY=false

while [[ $# -gt 0 ]]; do
  case $1 in
    --agent)        AGENTS="$2"; shift 2 ;;
    --secret-name)  SECRET_NAME="$2"; shift 2 ;;
    --region)       REGION="$2"; shift 2 ;;
    --refresh-token) REFRESH_ONLY=true; shift ;;
    -h|--help)      grep '^#' "$0" | sed 's/^# \{0,1\}//'; exit 0 ;;
    *) echo "error: unknown option $1 (see --help)"; exit 1 ;;
  esac
done

for bin in aws jq; do
  command -v "$bin" >/dev/null || {
    echo "error: $bin is required and was not found on PATH"; exit 1; }
done

CREDS="$(aws secretsmanager get-secret-value --secret-id "$SECRET_NAME" \
          --region "$REGION" --query SecretString --output text 2>/dev/null)" || {
  echo "error: cannot read the credentials secret '$SECRET_NAME' in"
  echo "       $REGION — your AWS identity needs secretsmanager:GetSecretValue"
  echo "       on it (or pass the right --secret-name / --region)"; exit 1; }
GATEWAY_URL="$(echo "$CREDS" | jq -r .endpointUrl)"
[[ "$GATEWAY_URL" == https://* ]] || {
  echo "error: the secret has no endpointUrl — is it the gateway credentials bundle?"; exit 1; }

# ── the ONE auth primitive: a wrapper with this deployment's secret
# name/region baked in, satisfying every helper contract (JSON headers
# on stdout; Claude Code re-runs per connect, Codex re-runs on 401).
# Named PER DEPLOYMENT so configuring a second gateway on this machine
# never silently repoints agents configured against the first. ──
DEPLOY_KEY=$(printf '%s|%s' "$SECRET_NAME" "$REGION" | shasum -a 256 2>/dev/null | cut -c1-16 \
             || printf '%s|%s' "$SECRET_NAME" "$REGION" | sha256sum | cut -c1-16)
WRAPPER="$HERE/gateway_headers.$DEPLOY_KEY.sh"
cat > "$WRAPPER" <<EOF
#!/usr/bin/env bash
# generated by configure.sh — headers helper for '$SERVER_KEY'
export GATEWAY_SECRET_NAME="$SECRET_NAME"
export AWS_REGION="$REGION"
exec "$HERE/get_gateway_token.sh"
EOF
chmod 700 "$WRAPPER"

mint_token() {  # always FRESH — never serve a cached token as "new"
  GATEWAY_TOKEN_NO_CACHE=1 bash "$WRAPPER" | jq -r .Authorization | cut -d' ' -f2
}

backup() { [[ -f "$1" ]] && cp "$1" "$1.bak.$(date +%Y%m%d%H%M%S)"; }

link_skills() {  # link_skills <target-dir>
  mkdir -p "$1"
  local d
  for d in "$KIT_ROOT"/skills/*/; do
    ln -sfn "${d%/}" "$1/$(basename "$d")"
  done
  echo "  skills linked into $1"
}

configure_kiro_token() {
  # WORKSPACE-level config, deliberately (./.kiro, beside the skills):
  # Kiro merges workspace over user level, so this entry can never be
  # shadowed — the user-level file is where a hand-rolled entry went
  # missing in practice. Run from the project you use Kiro in.
  local cfg="./.kiro/settings/mcp.json" token
  token="$(mint_token)"
  mkdir -p "$(dirname "$cfg")"
  [[ -s "$cfg" ]] || echo '{}' > "$cfg"
  backup "$cfg"
  # defaults only on a NEW entry — an existing autoApprove (e.g. ["*"])
  # is the user's call and survives the merge; we never default to "*"
  # because the bundle's gateway carries admin tools
  jq --arg url "$GATEWAY_URL" --arg tok "Bearer $token" \
     '.mcpServers."media-toolkit" =
        ((.mcpServers."media-toolkit"
          // {"disabled": false, "autoApprove": []}) +
         {"url": $url, "headers": {"Authorization": $tok}})' \
     "$cfg" > "$cfg.tmp" && mv "$cfg.tmp" "$cfg"
  chmod 600 "$cfg"
  echo "  $cfg updated (token valid ~12 h; re-run with --refresh-token"
  echo "  from this project; Kiro hot-reloads the file on save)"
  # the file carries a bearer token — it must never be committed
  if git rev-parse --is-inside-work-tree >/dev/null 2>&1 \
     && ! git check-ignore -q "$cfg" 2>/dev/null; then
    echo "  WARNING: $cfg is NOT gitignored and contains a bearer token —"
    echo "           add '.kiro/' (or this file) to .gitignore before committing"
  fi
}

if $REFRESH_ONLY; then
  configure_kiro_token
  exit 0
fi

[[ -n "$AGENTS" ]] || {
  echo "error: --agent is required: claude, codex, kiro, or all"; exit 1; }
[[ "$AGENTS" == "all" ]] && AGENTS="claude,codex,kiro"

for agent in ${AGENTS//,/ }; do
  case $agent in

    claude)
      echo "Claude Code:"
      CFG="./.mcp.json"
      [[ -s "$CFG" ]] || echo '{}' > "$CFG"
      backup "$CFG"
      # merge INTO any existing entry (user-added fields survive);
      # only type/url/headersHelper are ours to set
      jq --arg url "$GATEWAY_URL" --arg helper "$WRAPPER" \
         '.mcpServers."media-toolkit" =
            ((.mcpServers."media-toolkit" // {}) +
             {"type": "http", "url": $url, "headersHelper": $helper})' \
         "$CFG" > "$CFG.tmp" && mv "$CFG.tmp" "$CFG"
      echo "  $CFG updated (auth auto-refreshes via headersHelper)"
      link_skills "./.claude/skills"
      echo "  NOTE: Claude Code asks you to approve this project-scoped"
      echo "        server on first launch — accept the prompt once."
      ;;

    codex)
      echo "Codex CLI:"
      CFG="$HOME/.codex/config.toml"
      mkdir -p "$(dirname "$CFG")"; touch "$CFG"
      backup "$CFG"
      # managed block: replace if present, append otherwise — never
      # touches the rest of the TOML
      python3 - "$CFG" "$GATEWAY_URL" "$WRAPPER" <<'PYEOF'
import re, sys
cfg, url, helper = sys.argv[1], sys.argv[2], sys.argv[3]
block = (
    "# >>> media-toolkit (managed by configure.sh) >>>\n"
    "[mcp_servers.media-toolkit]\n"
    f'url = "{url}"\n'
    f'http_headers_helper = "{helper}"\n'
    "# <<< media-toolkit <<<\n")
s = open(cfg).read()
pat = re.compile(r"# >>> media-toolkit.*?# <<< media-toolkit <<<\n",
                 re.DOTALL)
if pat.search(s):
    s = pat.sub(block, s)
else:
    # a hand-written table outside our markers would become a
    # DUPLICATE TOML table if we appended — refuse, never corrupt
    if re.search(r"^\s*\[mcp_servers\.media-toolkit\]", s, re.M):
        sys.exit("error: ~/.codex/config.toml already defines "
                 "[mcp_servers.media-toolkit] outside the managed "
                 "block — remove or rename that table, then re-run")
    s = s + ("\n" if s and not s.endswith("\n") else "") + block
open(cfg, "w").write(s)
PYEOF
      echo "  $CFG updated (auth auto-refreshes via http_headers_helper)"
      link_skills "./.agents/skills"
      ;;

    kiro)
      echo "Kiro:"
      configure_kiro_token
      link_skills "./.kiro/skills"
      ;;

    *)
      echo "error: unknown agent '$agent' — claude, codex, kiro, or all"
      exit 1 ;;
  esac
done

echo
echo "Done. Gateway: $GATEWAY_URL"
echo "Smoke test: ask your agent to call a *___describe_tool and"
echo "summarize the output contract."
